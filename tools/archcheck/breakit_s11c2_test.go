// QA's break-it of S1.1c-2 (BK-S1): -cases counts a Go case as asserting when a Fatal, Error or FailNow on its T
// appears anywhere in its body, live or not. The Python strength rule (gate/runner/teeth.py) refuses a red helper
// after a return or under if False; the Go rule (design §4.2, DA-S12) has no live-code clause, so a pinned Go proof
// case hollowed by an if false or by a closure it never calls keeps its count and passes the pin. (A return at the
// top is the vet row's: unreachable code.)
func TestBreakitCasesDeadVerdicts(t *testing.T) {
	t.Parallel()
	const head = "package x\n\nimport \"testing\"\n\n"
	for _, c := range []struct{ name, src string }{
		{"the Fatal under if false", "func TestA(t *testing.T) {\n\tif false {\n\t\tt.Fatal(\"never\")\n\t}\n}\n"},
		{"the Fatal in a closure never called", "func TestA(t *testing.T) {\n\t_ = func() { t.Fatal(\"never\") }\n}\n"},
	} {
		t.Run(c.name, func(t *testing.T) {
			cases, faults := Cases("x_test.go", head+c.src)
			if !slices.Equal(cases, []string{"TestA"}) {
				t.Fatalf("cases %q, want [TestA]", cases)
			}
			if !slices.Contains(faults, "TestA: "+noVerdict) {
				t.Errorf("faults %q: %s counted as a verdict", faults, c.name)
			}
		})
	}
}

// BK-S3: a list target whose file still exists but which waives nothing is reported by neither mode. Stale reads
// only whether the path is gone; nothing reads whether the entry is used. A testhygiene entry left behind after its
// sleep is removed stays a live waiver: a sleep added back to the file later is green, and no LAW Δ line names it
// (tools/allowlists/ did not change). The same holds for a purity target whose package no longer imports the
// identifier and a clock target whose file no longer imports time.
func TestBreakitUnusedTestHygieneTarget(t *testing.T) {
	t.Parallel()
	const file = "internal/x/a_test.go"
	root := listRoot(t, nil, nil, []string{file})
	touch(t, root, file) // "package x\n": no time, nothing to waive
	code, out := runCLI(t, root, true, file)
	if code != 1 || !strings.Contains(out, file) {
		t.Fatalf("-tests: exit %d, output %q: an entry that waives nothing is not reported", code, out)
	}
}

// BK-B4: -cases parses a file go test never compiles. A pinned Go proof hollowed by a build constraint keeps its
// path, its cases and its verdict calls, so the instrument pin is green while the unit row never runs it (no
// event, nothing red). Checked on the real tree: `//go:build ignore` atop internal/parser/errorcounts_test.go
// left test_instruments_pin.RealTree green and dropped TestErrorCountsMatchTheCatalogue from `go test -list`.
func TestBreakitCasesBuildConstrainedFile(t *testing.T) {
	t.Parallel()
	const body = "package x\n\nimport \"testing\"\n\nfunc TestA(t *testing.T) { t.Fatal(\"x\") }\n"
	for name, constraint := range map[string]string{
		"go:build ignore": "//go:build ignore\n\n",
		"+build never":    "// +build never\n\n",
	} {
		t.Run(name, func(t *testing.T) {
			_, faults := Cases("x_test.go", constraint+body)
			if len(faults) == 0 {
				t.Errorf("no fault: a proof file go test never compiles is counted")
			}
		})
	}
}

// BK-S6: the generated-code header is an exemption (globalscheck here; the coverage floor in gate/coverage) with no
// anti-forgery since freshness was annotated moot. ADR-0015 §2.1 reads it on the first line only; generated()
// takes it from any comment anywhere in the file, so a hand-written file with the line at its foot escapes the
// globals check.
func TestBreakitGeneratedHeaderAnywhere(t *testing.T) {
	t.Parallel()
	src := "package x\n\nvar state = map[string]int{}\n\n// Code generated by hand. DO NOT EDIT.\n"
	file, err := parser.ParseFile(token.NewFileSet(), "x.go", src, parser.ParseComments)
	if err != nil {
		t.Fatal(err)
	}
	if generated(file) {
		t.Errorf("a header after the package clause marks the file generated (ADR-0015 §2.1: the first line)")
	}
}
