"""The coverage-inclusion command line (plan check S6, design note §5): flags, defaults, scope and exit codes.

The scope is `go list` over ./internal/... . ./rule/... ./io/... in --module-dir, so each test writes a small module.
"""

import os
import sys

from gate.coverage.tests import support
from gate.coverage.tests.test_classify import CLASSES

HEADER = "// Code generated by hand. DO NOT EDIT.\n"
PROFILE_A = "mode: set\nex.com/m/internal/a/a.go:3.16,3.26 1 1\n"
EVENTS_A = (
    '{"Action":"run","Package":"ex.com/m/internal/a","Test":"TestA"}\n'
    '{"Action":"pass","Package":"ex.com/m/internal/a","Test":"TestA","Elapsed":0}\n'
    '{"Action":"pass","Package":"ex.com/m/internal/a","Elapsed":0.1}\n'
)
FIX = "fix: each FAIL package needs tests that build, run and cover at least 90% of its statements (ADR-0015 §2.2)"


class Command(support.CoverageTest):
    def setUp(self):
        super().setUp()
        self.module = os.path.join(self.root, "m")
        self.write("m/go.mod", "module ex.com/m\n\ngo 1.27.0\n")

    def package(self, rel: str, *files: tuple[str, str]) -> None:
        name = rel.rsplit("/", 1)[-1]
        for file, head in files or (("a.go", ""),):
            self.write(f"m/{rel}/{file}", f"{head}package {name}\n\nfunc F() int {{ return 1 }}\n")

    def artifacts(self, profile: str | bytes = PROFILE_A, events: str | bytes = EVENTS_A) -> list[str]:
        return ["--profile", self.write("cover.prof", profile), "--events", self.write("test.json", events)]

    def main(
        self, *args: str, module_dir: str | None = None, floor: str | None = "90", **env: str
    ) -> tuple[int, list[str]]:
        # --floor is required (S1.1c-2 design §4.4): the registry passes --floor 90; floor=None leaves it out.
        argv = [sys.executable, "-I", "-B", "-X", "utf8", support.MAIN, *args]
        if floor is not None and "--floor" not in args:
            argv += ["--floor", floor]
        if module_dir is not None or "--module-dir" not in args:
            argv += ["--module-dir", module_dir or self.module]
        code, out, _ = support.run(argv, self.root, support.go_env(**env), self.root, "main")
        return code, out.split("\n")[:-1]


class Classes(Command):
    def test_every_class_through_the_command_line(self):
        for name in ("build", "c29", "crashed", "eightnine", "full", "ninety", "notests", "skipped", "zero"):
            self.package(f"internal/{name}")
        self.package("internal/zerofail")
        self.package("internal/gen", ("real.go", ""), ("gen.go", HEADER))
        self.package("internal/allgen", ("g.go", HEADER))
        self.package("outside")  # in the profile, but never in scope
        profile = ["--profile", os.path.join(support.TESTDATA, "classes.prof")]
        events = ["--events", os.path.join(support.TESTDATA, "classes.json")]
        code, out = self.main(*profile, *events)
        self.assertEqual(out, [*CLASSES, FIX, "GATE_COVERED 12"])
        self.assertEqual(code, 1)

    def test_all_passing_exits_0_and_prints_no_fix(self):
        self.package("internal/a")
        self.assertEqual(
            self.main(*self.artifacts()), (0, ["PASS ex.com/m/internal/a 100.00% (1/1) >= 90%", "GATE_COVERED 1"])
        )

    def test_the_floor_flag(self):
        self.package("internal/a")
        profile = "mode: set\nex.com/m/internal/a/a.go:3.16,3.26 9 1\nex.com/m/internal/a/a.go:4.1,4.2 1 0\n"
        code, out = self.main(*self.artifacts(profile), "--floor", "91")
        self.assertEqual((code, out[0]), (1, "FAIL ex.com/m/internal/a 90.00% (9/10) < 91%"))
        code, out = self.main(*self.artifacts(profile), "--floor", "90")
        self.assertEqual((code, out[0]), (0, "PASS ex.com/m/internal/a 90.00% (9/10) >= 90%"))


class Defaults(Command):
    def row_dirs(self) -> tuple[str, str]:
        rows = os.path.join(self.root, "run", "rows", "test")
        return os.path.join(rows, "unit"), os.path.join(rows, "coverage-inclusion")

    def test_the_unit_rows_artifacts_beside_this_rows_directory(self):
        unit, mine = self.row_dirs()
        self.write(os.path.join(unit, "cover.prof"), PROFILE_A)
        self.write(os.path.join(unit, "test.json"), EVENTS_A)
        os.makedirs(mine)
        self.package("internal/a")
        self.assertEqual(
            self.main(GATE_ROW_DIR=mine), (0, ["PASS ex.com/m/internal/a 100.00% (1/1) >= 90%", "GATE_COVERED 1"])
        )

    def test_a_missing_floor_is_the_usage_error(self):
        # S1.1c-2 design §4.4: no default floor; a missing --floor is the module's usage error, exit 2.
        unit, mine = self.row_dirs()
        self.write(os.path.join(unit, "cover.prof"), PROFILE_A)
        self.write(os.path.join(unit, "test.json"), EVENTS_A)
        os.makedirs(mine)
        self.package("internal/a")
        code, out = self.main(floor=None, GATE_ROW_DIR=mine)
        self.assertEqual(code, 2, out)
        self.assertEqual(out[0], "the following arguments are required: --floor")
        self.assertEqual(out[-2:], ["GATE FAILED", "exit: 2"])

    def test_a_missing_artifact_fails_naming_unit(self):
        # design-QA counter-example 34: unit died before writing cover.prof; this row still runs, and names unit.
        unit, mine = self.row_dirs()
        os.makedirs(mine)
        self.package("internal/a")
        for present in ((), ("test.json",), ("cover.prof",)):
            with self.subTest(present=present):
                os.makedirs(unit, exist_ok=True)
                for name in os.listdir(unit):
                    os.unlink(os.path.join(unit, name))
                for name in present:
                    self.write(os.path.join(unit, name), PROFILE_A if name == "cover.prof" else EVENTS_A)
                code, out = self.main(GATE_ROW_DIR=mine)
                self.assertEqual(code, 1)
                self.assertEqual(out[-1], "GATE_COVERED 0")
                for name in {"cover.prof", "test.json"} - set(present):
                    path = os.path.join(unit, name)
                    self.assertIn(f"FAIL {path} is missing: the unit row did not write it", out)

    def test_an_events_file_with_no_events_names_unit(self):
        unit, mine = self.row_dirs()
        self.write(os.path.join(unit, "cover.prof"), PROFILE_A)
        self.write(os.path.join(unit, "test.json"), "")
        os.makedirs(mine)
        self.package("internal/a")
        code, out = self.main(GATE_ROW_DIR=mine)
        path = os.path.join(unit, "test.json")
        self.assertEqual(
            (code, out), (1, [f"FAIL {path} holds no events: the unit row did not finish", "GATE_COVERED 0"])
        )

    def test_explicit_paths_need_no_row_directory(self):
        self.package("internal/a")
        self.assertEqual(self.main(*self.artifacts())[0], 0)

    def test_no_row_directory_and_no_paths_is_a_usage_error(self):
        self.package("internal/a")
        code, out = self.main()
        self.assertEqual(code, 2)
        self.assertEqual(out[-2:], ["GATE FAILED", "exit: 2"])
        self.assertIn("GATE_ROW_DIR", out[0])


class Scope(Command):
    def test_patterns_that_match_nothing_are_not_an_error(self):
        # C30: no root package, no rule/, no io/; the expansion is internal/a alone.
        self.package("internal/a")
        self.assertEqual(
            self.main(*self.artifacts()), (0, ["PASS ex.com/m/internal/a 100.00% (1/1) >= 90%", "GATE_COVERED 1"])
        )

    def test_the_root_rule_and_io_packages_enter_scope_with_no_flag(self):
        # ADR-0015 §2.2: internal/* + cep + rule + io + the io/* packages; cmd, bench, gate and the rest never.
        self.package("internal/a")
        self.write("m/cep.go", "package cep\n\nfunc F() int { return 1 }\n")
        for rel in ("internal/deep/er", "rule", "rule/x", "io", "io/kafka", "cmd/x", "bench/x", "gate/x", "tools/x"):
            self.package(rel)
        code, out = self.main(*self.artifacts())
        self.assertEqual(code, 1)
        self.assertEqual(
            out[:7],
            [
                "FAIL ex.com/m no tests",
                "PASS ex.com/m/internal/a 100.00% (1/1) >= 90%",
                "FAIL ex.com/m/internal/deep/er no tests",
                "FAIL ex.com/m/io no tests",
                "FAIL ex.com/m/io/kafka no tests",
                "FAIL ex.com/m/rule no tests",
                "FAIL ex.com/m/rule/x no tests",
            ],
        )
        self.assertEqual(out[7:], [FIX, "GATE_COVERED 7"])

    def test_a_directory_without_go_files_is_not_a_package(self):
        self.package("internal/a")
        self.write("m/internal/docs/README.md", "no Go here\n")
        self.assertEqual(self.main(*self.artifacts())[1][-1], "GATE_COVERED 1")

    def test_nothing_in_scope_is_a_failure(self):
        self.package("cmd/x")
        code, out = self.main(*self.artifacts())
        self.assertEqual((code, out), (1, ["FAIL no package in scope: zero is a failure", "GATE_COVERED 0"]))

    def test_go_list_failing_is_a_failure_naming_it(self):
        os.unlink(os.path.join(self.module, "go.mod"))
        self.package("internal/a")
        code, out = self.main(*self.artifacts())
        self.assertEqual(code, 1)
        self.assertTrue(out[0].startswith("FAIL go list exit 1: "), out)
        self.assertEqual(out[-1], "GATE_COVERED 0")


class Generated(Command):
    """ADR-0015 §2.1: a file whose first line matches ^// Code generated .* DO NOT EDIT\\.$ is out of both sides."""

    PROFILE = "mode: set\nex.com/m/internal/a/a.go:3.16,3.26 1 1\nex.com/m/internal/a/g.go:3.16,3.26 1 0\n"

    def judged(self, head: str) -> str:
        self.package("internal/a", ("a.go", ""), ("g.go", head))
        code, out = self.main(*self.artifacts(self.PROFILE))
        return out[0]

    def test_the_header_on_the_first_line_excludes_the_file(self):
        self.assertEqual(self.judged(HEADER), "PASS ex.com/m/internal/a 100.00% (1/1) >= 90%")

    def test_anything_else_counts_the_file(self):
        counted = "FAIL ex.com/m/internal/a 50.00% (1/2) < 90%"
        cases = {
            "the header on the second line": "// a comment\n" + HEADER,
            "a carriage return before the newline": HEADER.replace("\n", "\r\n"),
            "no generator named": "// Code generated DO NOT EDIT.\n",
            "no final period": "// Code generated by hand. DO NOT EDIT\n",
            "a block comment": "/* Code generated by hand. DO NOT EDIT. */\n",
        }
        for why, head in cases.items():
            with self.subTest(why=why):
                self.assertEqual(self.judged(head), counted)


class Malformed(Command):
    def test_a_malformed_profile_fails_naming_its_line(self):
        self.package("internal/a")
        code, out = self.main(*self.artifacts("mode: set\nnot a block\n"))
        self.assertEqual(code, 1)
        self.assertRegex(out[0], r"^FAIL .*cover\.prof: line 2: not a profile block")
        self.assertEqual(out[-1], "GATE_COVERED 0")

    def test_malformed_events_fail_naming_their_line(self):
        self.package("internal/a")
        code, out = self.main(*self.artifacts(events=EVENTS_A + "garbage\n"))
        self.assertEqual(code, 1)
        self.assertRegex(out[0], r"^FAIL .*test\.json: line 4: not JSON")
        self.assertEqual(out[-1], "GATE_COVERED 0")


class Usage(Command):
    def test_a_floor_must_be_a_decimal_from_1_to_100(self):
        self.package("internal/a")
        for floor in ("0", "101", "abc", "٩٠", " 90", "90.5", "+90", "090", ""):
            with self.subTest(floor=floor):
                code, out = self.main(*self.artifacts(), "--floor", floor)
                self.assertEqual((code, out[-2:]), (2, ["GATE FAILED", "exit: 2"]))
        for floor in ("1", "100"):
            with self.subTest(floor=floor):
                self.assertEqual(self.main(*self.artifacts(), "--floor", floor)[0], 0)

    def test_an_unknown_argument_is_a_usage_error(self):
        self.package("internal/a")
        for extra in (["./..."], ["--scope", "./..."], ["--flor", "90"]):
            with self.subTest(extra=extra):
                code, out = self.main(*self.artifacts(), *extra)
                self.assertEqual((code, out[-2:]), (2, ["GATE FAILED", "exit: 2"]))

    def test_a_module_dir_that_is_not_a_directory_is_a_usage_error(self):
        code, out = self.main(*self.artifacts(), module_dir=os.path.join(self.root, "nowhere"))
        self.assertEqual((code, out[-2:]), (2, ["GATE FAILED", "exit: 2"]))

    def test_a_crash_is_exit_2_never_exit_1(self):
        # Exit 1 means "coverage failed"; an internal error must not pass for it.
        self.package("internal/a")
        code, out = self.main("--profile", self.root, "--events", self.write("test.json", EVENTS_A))
        self.assertEqual(code, 2)
        self.assertTrue(out[0].startswith("internal error: IsADirectoryError"), out)
        self.assertEqual(out[-2:], ["GATE FAILED", "exit: 2"])
