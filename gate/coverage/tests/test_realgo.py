"""The instrument on real `go test` output (pinned go1.27.3), made by the unit row's own wrapper and its exact flags.

The unit wrapper writes into rows/test/unit/, and the instrument, as rows/test/coverage-inclusion, finds the
artifacts beside it by default (plan check S3d). Plan check C28, C31, C32 and the 9/10 and 8/9 boundaries.
Every expected line is by hand: `func Fi() int { return i }` is one statement.
"""

import os
import shutil
import sys

from gate.coverage.tests import support

UNIT = os.path.join(support.REPO, "gate", "runner", "rows", "unit.py")
PROOFS = os.path.join(support.REPO, "gate", "proofs")
HEADER = "// Code generated by hand. DO NOT EDIT.\n\n"


def funcs(package: str, n: int, head: str = "", prefix: str = "F") -> str:
    return head + f"package {package}\n" + "".join(f"\nfunc {prefix}{i}() int {{ return {i} }}\n" for i in range(n))


def test_calling(package: str, names: list[str], imports: str = "") -> str:
    body = "".join(f"\t{name}()\n" for name in names)
    return f'package {package}\n\nimport (\n\t"testing"\n{imports})\n\nfunc TestCalls(t *testing.T) {{\n{body}}}\n'


class RealGo(support.CoverageTest):
    def module(self, path: str, files: dict[str, str]) -> str:
        self.write("m/go.mod", f"module {path}\n\ngo 1.27.0\n")
        for rel, text in files.items():
            self.write(f"m/{rel}", text)
        return os.path.join(self.root, "m")

    def unit_then_coverage(self, module: str) -> tuple[int, int, list[str]]:
        rows = os.path.join(self.root, "run", "rows", "test")
        unit, mine = os.path.join(rows, "unit"), os.path.join(rows, "coverage-inclusion")
        os.makedirs(unit)
        os.makedirs(mine)
        py = [sys.executable, "-I", "-B", "-X", "utf8"]
        unit_code, _, _ = support.run([*py, UNIT, "./..."], module, support.go_env(GATE_ROW_DIR=unit), unit, "unit")
        code, out, err = support.run([*py, support.MAIN], module, support.go_env(GATE_ROW_DIR=mine), mine, "main")
        self.assertEqual(err, "")
        return unit_code, code, out.split("\n")[:-1]

    def test_every_class_from_a_real_go_test_run(self):
        module = self.module(
            "ex.com/r",
            {
                "internal/zero/z.go": "package zero\n\nconst C = 1\n\ntype T int\n",
                "internal/zero/z_test.go": test_calling("zero", []),
                "internal/onlyx/o_test.go": test_calling("onlyx_test", []),
                "internal/notests/n.go": funcs("notests", 1),
                "internal/build/b.go": funcs("build", 1),
                "internal/build/b_test.go": 'package build\n\nvar x int = "s"\n',
                "internal/skipped/s.go": funcs("skipped", 1),
                "internal/skipped/s_test.go": 'package skipped\n\nimport "testing"\n\n'
                'func TestA(t *testing.T) { t.Skip("x") }\n\nfunc TestB(t *testing.T) { t.Skip("y") }\n',
                "internal/crashed/c.go": funcs("crashed", 1),
                "internal/crashed/c_test.go": 'package crashed\n\nimport "testing"\n\n'
                'func TestA(t *testing.T) { F0() }\n\nfunc TestB(t *testing.T) { panic("boom") }\n',
                "internal/ninety/n.go": funcs("ninety", 10),
                "internal/ninety/n_test.go": test_calling("ninety", [f"F{i}" for i in range(9)]),
                "internal/eightnine/e.go": funcs("eightnine", 9),
                "internal/eightnine/e_test.go": test_calling("eightnine", [f"F{i}" for i in range(8)]),
                "internal/gen/real.go": funcs("gen", 1),
                "internal/gen/gen.go": funcs("gen", 5, HEADER, prefix="G"),
                "internal/gen/g_test.go": test_calling("gen", ["F0"]),
            },
        )
        unit_code, code, out = self.unit_then_coverage(module)
        self.assertEqual(unit_code, 1)  # the build failure and the panic fail the unit row too
        self.assertEqual(
            out,
            [
                "FAIL ex.com/r/internal/build build failed",  # C28 (b)
                "FAIL ex.com/r/internal/crashed missing from the profile",  # a test passed, then the binary died
                "FAIL ex.com/r/internal/eightnine 88.88% (8/9) < 90%",
                "PASS ex.com/r/internal/gen 100.00% (1/1) >= 90%",  # gen.go's five statements are out of both sides
                "PASS ex.com/r/internal/ninety 90.00% (9/10) >= 90%",
                "FAIL ex.com/r/internal/notests no tests",  # C28 (c)
                "PASS ex.com/r/internal/onlyx n/a (0 statements)",  # external tests only
                "FAIL ex.com/r/internal/skipped no test ran",  # C31
                "PASS ex.com/r/internal/zero n/a (0 statements)",  # C28 (a)
                "fix: each FAIL package needs tests that build, run and cover at least 90% of its statements "
                "(ADR-0015 §2.2)",
                "GATE_COVERED 9",
            ],
        )
        self.assertEqual(code, 1)

    def test_only_a_packages_own_tests_count(self):
        # C32: b's test calls a.F1, but unit passes no -coverpkg, so a is measured by its own test alone.
        module = self.module(
            "ex.com/c",
            {
                "internal/a/a.go": funcs("a", 2),
                "internal/a/a_test.go": test_calling("a", ["F0"]),
                "internal/b/b.go": funcs("b", 1),
                "internal/b/b_test.go": test_calling("b", ["F0", "a.F1"], '\t"ex.com/c/internal/a"\n'),
            },
        )
        unit_code, code, out = self.unit_then_coverage(module)
        self.assertEqual(unit_code, 0)
        self.assertEqual(out[0], "FAIL ex.com/c/internal/a 50.00% (1/2) < 90%")
        self.assertEqual(out[1], "PASS ex.com/c/internal/b 100.00% (1/1) >= 90%")
        self.assertEqual((out[-1], code), ("GATE_COVERED 2", 1))

    def test_the_planted_proofs_packages_measure_as_designed(self):
        # gate/proofs (design note §8): below 8 of 9 statements covered, notests without a test, control fully covered;
        # racy (the race row's proof, 2026-11-05) 9 of 9: its race shows only under -race, never in coverage. leaky
        # (the leak proof, S3.2b-2) fails the unit row by design, as test_leak_planted.py proves: it is left out here.
        module = os.path.join(self.root, "m")
        shutil.copytree(
            os.path.join(PROOFS, "internal"), os.path.join(module, "internal"), ignore=shutil.ignore_patterns("leaky")
        )
        shutil.copy(os.path.join(PROOFS, "go.mod"), module)
        unit_code, code, out = self.unit_then_coverage(module)
        self.assertEqual(unit_code, 0)
        self.assertEqual(
            out[:4],
            [
                "FAIL github.com/vorsar/cep/gate/proofs/internal/below 88.88% (8/9) < 90%",
                "PASS github.com/vorsar/cep/gate/proofs/internal/control 100.00% (4/4) >= 90%",
                "FAIL github.com/vorsar/cep/gate/proofs/internal/notests no tests",
                "PASS github.com/vorsar/cep/gate/proofs/internal/racy 100.00% (9/9) >= 90%",
            ],
        )
        self.assertEqual((out[-1], code), ("GATE_COVERED 4", 1))
